import { expect, test } from '@playwright/test'

const shots = process.env.SHOTS

test('plays a sol from the title to the report', async ({ page }, info) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /SolSurvivor/ })).toBeVisible()
  if (shots) await page.screenshot({ path: `${shots}/${info.project.name}-title.png` })
  await page.getByRole('button', { name: /Start mission/ }).click()
  await page.getByRole('button', { name: 'Skip tips' }).click()
  await page.getByRole('button', { name: 'More Oxygen maker' }).click()
  await page.getByRole('button', { name: 'More Oxygen maker' }).click()
  await page.getByRole('button', { name: 'More Greenhouse lights' }).click()
  await page.getByRole('button', { name: 'More Talk to Earth' }).click()
  await page.locator('[data-project="landing"] button').click()
  await expect(page.getByText('3 of 8 left')).toBeVisible()
  if (shots) await page.screenshot({ path: `${shots}/${info.project.name}-plan.png`, fullPage: true })
  await page.getByRole('button', { name: /End sol/ }).click()
  await expect(page.getByRole('dialog', { name: 'Sol 1 report' })).toBeVisible()
  await expect(page.getByText(/Landing site finished/)).toBeVisible()
  if (shots) await page.screenshot({ path: `${shots}/${info.project.name}-report.png` })
  await page.getByRole('button', { name: 'Next sol' }).click()
  await expect(page.getByText('Sol 2 of 10')).toBeVisible()
  await expect(page.getByRole('button', { name: /Same plan again/ })).toBeVisible()
})

test('Arabic: right to left, translated, and switchable mid-mission', async ({ page }, info) => {
  await page.goto('/?lang=ar')
  await expect(page.locator('html')).toHaveAttribute('dir', 'rtl')
  await page.getByRole('button', { name: /ابدأ المهمة/ }).click()
  await page.getByRole('button', { name: 'تخطَّ النصائح' }).click()
  await page.getByRole('button', { name: 'أكثر: صانع الأكسجين' }).click()
  await page.locator('[data-project="landing"] button').click()
  await expect(page.getByText('السول 1 من 10')).toBeVisible()
  await expect(page.getByText('بعد سولين').first()).toBeVisible()
  if (shots) await page.screenshot({ path: `${shots}/${info.project.name}-ar-plan.png` })
  await page.getByRole('button', { name: /إنهاء السول/ }).click()
  await expect(page.getByRole('dialog', { name: 'تقرير السول 1' })).toBeVisible()
  if (shots) await page.screenshot({ path: `${shots}/${info.project.name}-ar-report.png` })
  await page.getByRole('button', { name: 'السول التالي' }).click()
  await page.getByRole('button', { name: 'English' }).click()
  await expect(page.locator('html')).toHaveAttribute('dir', 'ltr')
  await expect(page.getByText('Sol 2 of 10')).toBeVisible()
})

test('the Moon: days instead of sols, in English and Arabic', async ({ page }, info) => {
  await page.goto('/?lang=en')
  await page.getByRole('radio', { name: /Moon/ }).click()
  await expect(page.getByText(/south pole/).first()).toBeVisible()
  if (shots) await page.screenshot({ path: `${shots}/${info.project.name}-moon-title.png` })
  await page.getByRole('button', { name: /Start mission/ }).click()
  await page.getByRole('button', { name: 'Skip tips' }).click()
  await expect(page.getByText('Day 1 of 10')).toBeVisible()
  await expect(page.getByText(/Welcome to the Moon/)).toBeVisible()
  await expect(page.locator('[data-project="landing"]')).toContainText('Landing zone')
  if (shots) await page.screenshot({ path: `${shots}/${info.project.name}-moon-plan.png` })
  await page.getByRole('button', { name: 'عربي' }).click()
  await expect(page.getByText('اليوم 1 من 10')).toBeVisible()
  await expect(page.locator('[data-project="landing"]')).toContainText('منطقة الهبوط')
})

test('live solar flares appear on the title when online', async ({ page }, info) => {
  test.skip(info.project.name !== 'desktop', 'one browser is enough')
  await page.goto('/?lang=en')
  const card = page.getByRole('complementary', { name: 'Live from the Sun' })
  await expect(card).toBeVisible({ timeout: 15000 })
  await expect(card).toContainText(/Live data: (NASA DONKI|NOAA GOES)/)
  if (shots) await page.screenshot({ path: `${shots}/${info.project.name}-title-live.png` })
})
